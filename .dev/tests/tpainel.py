import asyncio
from playwright.async_api import async_playwright
B='http://localhost:8811/painel.html'; res=[]
def ok(c,m): res.append(('PASS ' if c else 'FAIL ')+m)
async def main():
  async with async_playwright() as p:
    b=await p.chromium.launch(); errs=[]
    for w in [320,390]:
     for sch in ['light','dark']:
      ctx=await b.new_context(viewport={'width':w,'height':780},device_scale_factor=2,color_scheme=sch)
      pg=await ctx.new_page(); pg.on('pageerror',lambda e: errs.append(str(e)))
      await pg.goto(B); await pg.wait_for_timeout(500)
      t=await pg.inner_text('body')
      ok('Criar conta' not in t and 'Google' not in t,'sem criar conta e sem Google')
      await pg.fill('#lEmail','x@x.com'); await pg.fill('#lSenha','errada'); await pg.click('#lBtn'); await pg.wait_for_timeout(600)
      ok('não conferem' in await pg.inner_text('#lErr'),'senha errada recusa')
      await pg.screenshot(path=f't2/pn-{w}-{sch}-login.png')
      await pg.fill('#lEmail','caio@exemplo.com'); await pg.fill('#lSenha','demonstracao'); await pg.click('#lBtn'); await pg.wait_for_timeout(700)
      t=await pg.inner_text('body'); ok('Comissões este mês' in t and 'Olá, Caio' in t,'inicio')
      sw=await pg.evaluate('document.documentElement.scrollWidth'); ok(sw<=w,f'sem rolagem lateral inicio {sw}')
      await pg.screenshot(path=f't2/pn-{w}-{sch}-inicio.png',full_page=True)
      await pg.click('[data-act=aba][data-v=ofertas]'); await pg.wait_for_timeout(300)
      ok(await pg.locator('.row[data-act=abrir]').count()>=5,'ofertas no ar')
      ok(await pg.locator('.tag.imp').count()>=1 and await pg.locator('.tag.of').count()>=1,'imperdivel e discreta')
      sw=await pg.evaluate('document.documentElement.scrollWidth'); ok(sw<=w,f'sem rolagem lateral ofertas {sw}')
      await pg.screenshot(path=f't2/pn-{w}-{sch}-ofertas.png',full_page=True)
      await pg.fill('#qBusca','gela'); await pg.wait_for_timeout(200); ok(await pg.locator('.row[data-act=abrir]').count()==1,'busca')
      await pg.fill('#qBusca',''); await pg.wait_for_timeout(200)
      n0=await pg.locator('.row[data-act=abrir]').count()
      await pg.locator('.row[data-act=abrir]').first.click(); await pg.wait_for_timeout(400)
      await pg.screenshot(path=f't2/pn-{w}-{sch}-sheet.png')
      await pg.click('[data-bl="1"]'); await pg.wait_for_timeout(500)
      ok(await pg.locator('.row[data-act=abrir]').count()==n0-1,'bloquear tira do ar')
      await pg.click('[data-act=sub][data-v=bloq]'); await pg.wait_for_timeout(200)
      nb=await pg.locator('[data-act=desbloquear]').count(); ok(nb>=2,'aparece em bloqueadas')
      await pg.locator('[data-act=desbloquear]').first.click(); await pg.wait_for_timeout(300)
      ok(await pg.locator('[data-act=desbloquear]').count()==nb-1,'liberar')
      await pg.click('[data-act=aba][data-v=robo]'); await pg.wait_for_timeout(300)
      await pg.screenshot(path=f't2/pn-{w}-{sch}-robo.png',full_page=True)
      t=await pg.inner_text('body'); ok('5%' in t and '15%' in t,'regras 5 e 15')
      await pg.click('[data-act=mais][data-k=descontoMin]'); await pg.wait_for_timeout(900)
      d=await pg.evaluate("JSON.parse(localStorage.getItem('cozily-painel-demo')).config")
      ok(d['descontoMin']==6,'regra salva')
      for _ in range(12): await pg.click('[data-act=mais][data-k=descontoMin]')
      await pg.wait_for_timeout(900); d=await pg.evaluate("JSON.parse(localStorage.getItem('cozily-painel-demo')).config")
      ok(d['imperdivelMin']>=d['descontoMin'],'imperdivel nunca abaixo do minimo')
      sw=await pg.evaluate('document.documentElement.scrollWidth'); ok(sw<=w,f'sem rolagem lateral robo {sw}')
      await pg.click('[data-act=pausar]'); await pg.wait_for_timeout(300); ok('Robô pausado' in await pg.inner_text('body'),'pausar')
      await pg.click('[data-act=sair]'); await pg.wait_for_timeout(400); ok(await pg.locator('#lEmail').count()==1,'sair')
      await ctx.close()
    ok(not errs,'sem erros '+str(errs[:2]))
    await b.close()
  for r in res: print(r)
  print('FAILS',[r for r in res if r.startswith('FAIL')])
asyncio.run(main())
