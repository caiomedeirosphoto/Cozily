      code,msg=await gencode('Ana Souza','Parente')
      ok(msg.startswith('Oi, Ana!'),'msg personalised')
      ok('Ana Souza' in await pg.inner_text('.overlay') and 'Parente' in await pg.inner_text('.overlay'),'pending shows name+rel')
