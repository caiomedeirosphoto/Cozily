      await pg.click('#jCopy'); await pg.wait_for_timeout(400)
      clip=await pg.evaluate('navigator.clipboard.readText()'); ok(code in clip,'copy has same link')
      await pg.click('#jOutro'); await pg.wait_for_timeout(300)
      ok(await pg.input_value('#jQuem')=='' and await pg.input_value('#jRel')=='' and await pg.query_selector('#jCriar') is not None,'outro resets form')
      await pg.click('.convite-mail summary'); await pg.wait_for_timeout(300); await sh('1b-juntos-mail',True)
      await logout()
      # landing as new user
      await pg.goto(B+'?c='+code); await pg.wait_for_timeout(1200)
      t=await pg.inner_text('#app'); ok('te chamou' in t,'landing banner'); ok(await pg.input_value('#lNome')=='Ana Souza','name prefilled'); ok('?c=' not in pg.url,'url cleaned')
      await sh('2-landing',True)
      await pg.fill('#lEmail',f'ana-{scheme}@teste.com'); await pg.fill('#lSenha','123456'); (await pg.query_selector('#lSenha2')) and await pg.fill('#lSenha2','123456'); await pg.click('#lBtn'); await pg.wait_for_timeout(1800)
      t=await pg.inner_text('#app'); ok('Você entrou no' in t,'bemvindo screen'); await sh('3-bemvindo',True)
      await pg.click('[data-act=post-next]'); await pg.wait_for_timeout(500); await pg.click('[data-act=post-next] >> nth=-1'); await pg.wait_for_timeout(500)
      if await pg.query_selector('[data-act=post-next]'): await pg.click('[data-act=post-next] >> nth=-1'); await pg.wait_for_timeout(1500)
      ok(await pg.query_selector('.tour') is not None,'tour shown'); await sh('4-home-tour')
