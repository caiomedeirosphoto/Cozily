      await logout(); await pg.goto(B); await pg.wait_for_timeout(900); await login('caio@exemplo.com')
      code4,_=await gencode()
      await pg.click(f'[data-unl="{code4}"]'); await pg.wait_for_timeout(400)
      ex=await pg.evaluate(f"!!JSON.parse(localStorage.getItem('cozily-preview-v6')).codigos['{code4}']"); ok(not ex,'cancel deletes code')
      # inviter opens own link
      await pg.goto(B+'?c='+code3); await pg.wait_for_timeout(1500)
      ok(await pg.query_selector('[data-act=cod-sim]') is None,'own/used link no confirm')
      # convite que não existe no servidor: não joga numa casa nova
      await logout(); await pg.goto(B+'?c=ZZZZZZZZZZZZZZZZZZZZZZ'); await pg.wait_for_timeout(2500)
      await pg.fill('#lNome','Lu'); await pg.fill('#lEmail',f'lu-{scheme}@teste.com'); await pg.fill('#lSenha','123456'); await pg.fill('#lSenha2','123456'); await pg.click('#lBtn'); await pg.wait_for_timeout(3500)
