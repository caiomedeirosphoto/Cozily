      casa=await pg.evaluate("JSON.parse(localStorage.getItem('cozily-preview-v6')).convites['ana-%s@teste.com'].casaId"%scheme); ok(casa=='nosso-ap','joined nosso-ap')
      await pg.click('[data-act=settings]'); await pg.wait_for_timeout(500); await pg.click('[data-go=juntos]'); await pg.wait_for_timeout(700)
      t=await pg.inner_text('#jList'); ok('Ana Souza · você' in t and 'Parente' in t and 'Caio' in t,'joined member has name+rel: '+t.replace(chr(10),' | ')[:200])
      await sh('4b-juntos-ana',True)
      # nameless own account -> edit name
      await pg.evaluate("(()=>{const d=JSON.parse(localStorage.getItem('cozily-preview-v6'));d.users[d.session].nome='';localStorage.setItem('cozily-preview-v6',JSON.stringify(d))})()")
      await pg.reload(); await pg.wait_for_timeout(1500)
      await pg.click('[data-act=settings]'); await pg.wait_for_timeout(500); await pg.click('[data-go=juntos]'); await pg.wait_for_timeout(700)
      ok(await pg.query_selector('#jNome') is not None,'nameless shows name field'); await sh('4c-semnome')
      await pg.fill('#jNome','Aninha'); await pg.click('#jNomeForm button'); await pg.wait_for_timeout(400)
      ok('Aninha · você' in await pg.inner_text('#jList'),'own name saved')
      await pg.reload(); await pg.wait_for_timeout(1200)
      # reuse used link
      await logout(); await pg.goto(B+'?c='+code); await pg.wait_for_timeout(1200)
      t=await pg.inner_text('#app'); ok('já foi usado' in t,'used link warns'); await sh('5-usado',True)
      # new account hitting used link -> error screen
      await pg.click('[data-act=authmode][data-v=criar]'); await pg.wait_for_timeout(200)
      await pg.fill('#lNome','Zé'); await pg.fill('#lEmail',f'ze-{scheme}@teste.com'); await pg.fill('#lSenha','123456'); (await pg.query_selector('#lSenha2')) and await pg.fill('#lSenha2','123456'); await pg.click('#lBtn'); await pg.wait_for_timeout(1500)
