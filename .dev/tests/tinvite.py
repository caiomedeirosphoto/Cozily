      t=await pg.inner_text('#app'); ok('Você entrou no' in t,'joined after confirm')
      links=await pg.evaluate("JSON.parse(localStorage.getItem('cozily-preview-v6')).casas['nosso-ap'].settings.links||[]")
      ok(all(l['c']!=code2 for l in links),'used link removed from pending')
      # verification flow
      await logout(); await pg.goto(B); await pg.wait_for_timeout(900); await login('caio@exemplo.com')
      code3,_=await gencode(); await logout()
      await pg.goto(B+'?c='+code3); await pg.wait_for_timeout(1200)
      await pg.fill('#lNome','Vi'); await pg.fill('#lEmail',f'vi+verificar-{scheme}@teste.com'); await pg.fill('#lSenha','123456'); (await pg.query_selector('#lSenha2')) and await pg.fill('#lSenha2','123456'); await pg.click('#lBtn'); await pg.wait_for_timeout(1500)
      ok('Confirma seu e-mail' in await pg.inner_text('#app'),'verify gate first')
